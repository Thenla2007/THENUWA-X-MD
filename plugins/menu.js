// 2. AUTOMATIC CATEGORY FILTERING LOGIC
// ==========================================
cmd({
    pattern: "submenu",
    dontAddCommandList: true,
    filename: __filename
}, async (robin, mek, m, { from, reply, text }) => {
    try {
        if (!text) return;
        
        const targetCategory = text.trim().toLowerCase();
        let menuMessage = "";
        let foundCommands = false;

        if (targetCategory === "all") {
            menuMessage = `📊 *DENETH-MD ALL COMMANDS LIST* 📊\n\n`;
            commands.map((cmd) => {
                if (!cmd.dontAddCommandList && cmd.pattern) {
                    menuMessage += `▪️ *Command:* .${cmd.pattern}\n▪️ *Desc:* ${cmd.desc || 'No description'}\n\n`;
                    foundCommands = true;
                }
            });
        } else {
            menuMessage = `✨ *DENETH-MD ${targetCategory.toUpperCase()} MENU* ✨\n\n`;
            commands.map((cmd) => {
                if (!cmd.dontAddCommandList && cmd.pattern && cmd.category && cmd.category.toLowerCase() === targetCategory) {
                    menuMessage += `▪️ *Command:* .${cmd.pattern}\n▪️ *Desc:* ${cmd.desc || 'No description'}\n\n`;
                    foundCommands = true;
                }
            });
        }

        if (!foundCommands) {
            menuMessage += `❌ මෙම Category එක යටතේ දැනට විධාන කිසිවක් හමු වූයේ නැත.`;
        } else {
            menuMessage += `> *© Powered by DENETH-MD*`;
        }

        return await robin.sendMessage(from, { text: menuMessage }, { quoted: mek });

    } catch (e) {
        console.error("SUBMENU ERROR:", e);
        reply(`❌ Sub Menu Error\n\n${e.message || e}`);
    }
});
